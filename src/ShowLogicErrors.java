public class ShowLogicErrors {
   public static void main() {
       System.out.println("Celsius 35 in Fahrenheit degree ");
       // testing division of integer and float numbers

       System.out.println((9/5.0) * 35 + 32); // result is 95.0, 9/5.0 is 1.8
       System.out.println((9/5) * 35 + 32); // result is 67, 9/5 is 1
    }
}
